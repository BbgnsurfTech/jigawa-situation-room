    /**
     * Seed all 774 LGAs across Nigeria organized by state.
     * Source: INEC Official List
     */
    public function run(): void
    {
        $states = State::all()->keyBy('code');

        if ($states->isEmpty()) {
            $this->command->error('StateSeeder must run first. Skipping LgaSeeder.');
            return;
        }

        $lgaData = $this->getLgaData();
        $count = 0;

        foreach ($lgaData as $stateCode => $lgas) {
            $state = $states[$stateCode] ?? null;
            if (!$state) {
                $this->command->warn("State {$stateCode} not found. Skipping its LGAs.");
                continue;
            }

            foreach ($lgas as $lga) {
                Lga::updateOrCreate(
                    ['code' => $lga['code']],
                    [
                        'name' => $lga['name'],
                        'state_id' => $state->id,
                    ]
                );
                $count++;
            }
        }

        $this->command->info("LgaSeeder: {$count} LGAs seeded across all states.");
    }

